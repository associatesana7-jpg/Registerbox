import assert from 'node:assert/strict';
import {validateDraft,reconcile} from '../supabase/functions/gst-returns/validation.ts';
import {sectionFingerprint} from '../supabase/functions/_shared/gstr1-sections.ts';
const gstin='29ABCDE1234F1Z5',period='082026';
const b2cs=[{pos:'29',sply_ty:'INTRA',typ:'OE',rt:18,txval:100,iamt:0,camt:9,samt:9,csamt:0}];
