assert.equal(reconcile(base,{...snapshot,registerbox_sections:{}},'gstr-1').matched,false);
assert.equal(reconcile(base,{...snapshot,registerbox_sections:{b2cs:[{...b2cs[0],txval:99}]}},'gstr-1').matched,false);
const exp={gstin,fp:period,exp:[{exp_typ:'WOPAY',inv:[{inum:'EXP-1',idt:'10-08-2026',val:100,itms:[{txval:100,rt:18,iamt:0,csamt:0}]}]}]};
