assert.throws(()=>validateDraft({...base,b2cs:[...b2cs,...b2cs]},'gstr-1',gstin,period),/Combine/);
assert.throws(()=>validateDraft({...base,b2cs:[{...b2cs[0],pos:'27'}]},'gstr-1',gstin,period),/supply type/);
const snapshot={sec_sum:[{sec_nm:'B2CS',ttl_tax:100}],registerbox_sections:{b2cs:b2cs.map(r=>({...r,chksum:'provider'}))}};
