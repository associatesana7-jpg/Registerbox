import assert from 'node:assert/strict';
import {validateBooks,unpack2b,normalize2b,matchPurchases,parsePurchaseCsv} from '../supabase/functions/_shared/gst-purchases.ts';
const gstin='29ABCDE1234F1Z5';
const book={supplier:'27ABCDE1234F1Z5',number:'INV-1',date:'10-08-2026',kind:'INV',taxable:100,igst:18,cgst:0,sgst:0,cess:0};
// Shape from Sandbox's GSTR-2B document API; entirely synthetic identifiers/amounts.
const invoice={inum:'INV-1',dt:'10-08-2026',txval:100,igst:18,cgst:0,sgst:0,cess:0,itcavl:'Y',rev:'N'};
const doc={gstin,rtnprd:'082026',docdata:{b2b:[{ctin:book.supplier,trdnm:'Test supplier',inv:[invoice]}]}};
const envelope={status_cd:'1',data:{chksum:'fixture',data:doc}};
assert.equal(unpack2b(envelope,gstin,'082026').data,doc);
assert.throws(()=>unpack2b(envelope,gstin,'072026'),/period/);
assert.throws(()=>unpack2b({status_cd:'0'},gstin,'082026'));
assert.equal(unpack2b({status_cd:'1',data:{data:{gstin,rtnprd:'082026',fc:2}}},gstin,'082026').files,2);
assert.throws(()=>normalize2b([{gstin,rtnprd:'082026'}]),/missing/);
const {rows}=normalize2b([doc]);
assert.equal(matchPurchases([book],rows).complete,true);
assert.equal(matchPurchases([{...book,igst:17}],rows).rows[0].status,'Amount mismatch');
assert.equal(matchPurchases([{...book,date:'11-08-2026'}],rows).rows[0].status,'Date mismatch');
assert.equal(matchPurchases([book],[]).rows[0].status,'Missing in 2B');
assert.equal(matchPurchases([],rows).rows[0].status,'Missing in books');
assert.equal(matchPurchases([book,book],rows).rows[0].status,'Duplicate');
assert.equal(matchPurchases([book],[{...rows[0],itcAvailable:'N'}]).rows[0].status,'Review required');
assert.equal(matchPurchases([book],rows,['IMPG']).complete,false);
const legacy={...doc,docdata:{b2b:[{ctin:book.supplier,inv:[{inum:'INV-1',dt:book.date,itcavl:'Y',rev:'N',items:[{txval:60,igst:10.8},{txval:40,igst:7.2}]}]}]}};
assert.equal(matchPurchases([book],normalize2b([legacy]).rows).complete,true);
assert.throws(()=>validateBooks([{...book,date:'31-02-2026'}]));
assert.throws(()=>validateBooks([{...book,cgst:9,sgst:9}]));
const csv='supplier,number,date,kind,taxable,igst,cgst,sgst,cess\r\n27ABCDE1234F1Z5,"INV,1",10-08-2026,INV,100,18,0,0,0';
assert.equal(parsePurchaseCsv(csv)[0].number,'INV,1');
assert.throws(()=>parsePurchaseCsv(csv.replace(',100,',',,')));
assert.throws(()=>parsePurchaseCsv(csv+'\ninvalid'));
console.log('Purchase matching, legacy/current 2B, pagination identity and atomic CSV tests passed. No live GST writes.');
