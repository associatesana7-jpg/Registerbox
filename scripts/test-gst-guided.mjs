import assert from 'node:assert/strict';
import {invoiceAmounts,appendInvoice} from '../src/lib/gst-invoice.ts';
import {validateNil,reviewNil,nilFilingPayload} from '../supabase/functions/gst-returns/nil.ts';
const gstin='29ABCDE1234F1Z5';
const input={customer:'29FGHIJ5678K1Z1',number:'TEST-1',date:'10-08-2026',pos:'29',taxable:'100',rate:'18',cess:'0'};
assert.equal(invoiceAmounts(input,gstin).cgst,9);
assert.equal(invoiceAmounts({...input,pos:'27'},gstin).igst,18);
assert.throws(()=>invoiceAmounts({...input,taxable:''},gstin));
const payload=appendInvoice({},input,gstin,'082026');
assert.throws(()=>appendInvoice(payload,input,gstin,'082026'),/already/);
assert.throws(()=>appendInvoice({},input,gstin,'072026'),/month/);
assert.throws(()=>validateNil({declarations:{}},'gstr-1'));
assert.equal(reviewNil({},'gstr-1').matched,false);
assert.equal(reviewNil({sec_sum:[{sec_nm:'B2B',ttl_rec:0,ttl_tax:0}]},'gstr-1').matched,true);
assert.equal(reviewNil({sec_sum:[{sec_nm:'B2B',ttl_rec:1,ttl_tax:0}]},'gstr-1').matched,false);
assert.equal(reviewNil({itc_elg:{itc_net:{iamt:200}}},'gstr-3b').matched,false);
assert.equal(nilFilingPayload('gstr-1',gstin,'082026').isnil,'Y');
assert.equal(nilFilingPayload('gstr-3b',gstin,'082026').isNil,'Y');
console.log('Guided invoice and nil-return safeguards passed. No provider writes performed.');
