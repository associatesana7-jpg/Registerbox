import assert from 'node:assert/strict';
import {questionsFor,documentsFor,validateQuestion,categoryFromLegacyPrompt,applicationCategories} from '../src/data/application-categories.ts';
import {parsePostalLocations,validateAddress} from '../src/data/india-address.ts';
assert.equal(categoryFromLegacyPrompt('apply for GST registration'),'gst_registration');
assert.equal(categoryFromLegacyPrompt('file a GST return'),'gst');
assert.equal(questionsFor('company',{}).filter(q=>q.kind==='address').length,1);
const questions=questionsFor('company',{directors:'2',director_1_nationality:'Indian',director_2_nationality:'Other'});
assert(questions.some(q=>q.key==='director_1_pan'));
assert(!questions.some(q=>q.key==='director_2_pan'));
assert(questions.some(q=>q.key==='director_2_passport'));
assert.equal(documentsFor('food',{food_activity:'Retail',water_used:'No'}).some(d=>d.type==='PREMISES_LAYOUT'),false);
assert.equal(documentsFor('food',{food_activity:'Manufacturing'}).some(d=>d.type==='PREMISES_LAYOUT'),true);
assert.equal(documentsFor('company',{directors:'2'}).filter(d=>d.type.includes('_IDENTITY')).length,2);
assert(validateQuestion(applicationCategories.company.questions.find(q=>q.key==='directors'),{directors:'1'}));
const location={pincode:'560001',state:'Karnataka',district:'Bangalore',city:'Bengaluru',address_line_1:'Test street',address_confirmed:'Yes'};
assert.equal(validateAddress(location),'');
assert(validateAddress({...location,pincode:'56000'}));
assert(validateAddress({...location,address_confirmed:'No'}));
assert.equal(parsePostalLocations([{Status:'Success',PostOffice:[{Pincode:'560001',Name:'Test',State:'Karnataka',District:'Bangalore'}]}],'560001')[0].state,'Karnataka');
assert.throws(()=>parsePostalLocations([{Status:'Success',PostOffice:[{Pincode:'110001'}]}],'560001'));
console.log('Category routing, conditional questions/docs, counts and PIN/address validation passed.');
