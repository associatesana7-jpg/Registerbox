import {validateDraft,reconcile} from '../supabase/functions/gst-returns/validation.ts';
import {blank3b,zeroBlanks} from '../supabase/functions/_shared/gstr3b.ts';
const context={gstin:'29ABCDE1234F1Z5',period:'092026',role:'seller'};
const row={source:'Platform',document:'INV-1',date:'2026-09-10',supplierGstin:context.gstin,recipientGstin:'',operatorGstin:'29FGHIJ5678K1Z1',pos:'29',treatment:'section9_5',kind:'invoice',originalDocument:'',originalPeriod:'',taxable:100,igst:0,cgst:2.5,sgst:2.5,cess:0};
const csv=(rows)=>PLATFORM_COLUMNS.join(',')+'\n'+rows.map(r=>PLATFORM_COLUMNS.map(k=>r[k]).join(',')).join('\n');
let initial={revision:0,rows:[],batches:[]};
let a=appendPlatformImport(initial,{name:'platform.csv',checksum:'a',csv:csv([row])},context);
assert.equal(a.workspace.rows.length,1);assert.equal(initial.rows.length,0);
assert.equal(a.workspace.batches[0].csv,csv([row]));
assert.equal(publicPlatformWorkspace(a.workspace).batches[0].csv,undefined);
let replay=appendPlatformImport(a.workspace,{name:'renamed.csv',checksum:'a',csv:csv([row])},context);
assert.equal(replay.workspace.revision,1);assert.equal(replay.duplicateFile,true);
let conflict=appendPlatformImport(a.workspace,{name:'pos.csv',checksum:'b',csv:csv([{...row,taxable:99},{...row,document:'INV-2'}])},context);
assert.equal(conflict.workspace.rows.length,1,'One conflict rejects whole source batch');
assert.equal(conflict.workspace.batches.length,2,'Rejected source evidence retained');
assert.equal(conflict.workspace.batches[1].accepted,0);
let duplicate=appendPlatformImport(a.workspace,{name:'pos.csv',checksum:'c',csv:csv([{...row,source:'POS'}])},context);
assert.equal(duplicate.workspace.rows.length,1);assert.equal(duplicate.workspace.batches[1].duplicates,1);
const one=addSellerPlatformDraft({gstin:context.gstin,fp:context.period},a.workspace.rows,context);
assert.equal(one.supeco.paytx[0].suppval,100);
assert.equal(validateDraft(one,'gstr-1',context.gstin,context.period),one);
assert.throws(()=>addSellerPlatformDraft(one,[row],context),/already/);
assert.throws(()=>addSellerPlatformDraft({gstin:context.gstin,fp:context.period},[{...row,treatment:'section52'}],context),/ordinary sales/);
assert.throws(()=>addSellerPlatformDraft({gstin:context.gstin,fp:context.period},[{...row,kind:'amendment',originalDocument:'old',originalPeriod:'082026'}],context),/14A/);
const snapshot={sec_sum:[{sec_nm:'SUPECO',ttl_tax:100}],registerbox_sections:{supeco:one.supeco}};
assert.equal(reconcile(one,snapshot,'gstr-1').matched,true);
assert.equal(reconcile(one,{...snapshot,registerbox_sections:{}},'gstr-1').matched,false);
const three=addSellerPlatform3b(zeroBlanks(blank3b(context.gstin,context.period)),[row],context);
assert.equal(three.eco_dtls.eco_reg_sup.txval,100);
assert.equal(three.eco_dtls.eco_sup.camt,0,'Seller must not pay platform tax again');
assert.equal(validateDraft(three,'gstr-3b',context.gstin,context.period),three);
assert.equal(reconcile(three,three,'gstr-3b').matched,true);
const changed=structuredClone(three);changed.eco_dtls.eco_reg_sup.txval=90;
