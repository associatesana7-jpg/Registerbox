const ordinary=zeroBlanks(blank3b(context.gstin,context.period));
assert.equal(reconcile(ordinary,three,'gstr-3b').matched,false,'Portal ecommerce figures cannot be silently omitted');
console.log('Persistent import and seller draft scenarios passed: source retention, replay, atomic conflicts, duplicate records, table 14(b), 3.1.1(ii), validation and reconciliation.');
