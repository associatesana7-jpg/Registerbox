import assert from 'node:assert/strict';
import {addOperatorPlatform3b} from '../supabase/functions/_shared/gst-platform-draft.ts';
import {blank3b,zeroBlanks} from '../supabase/functions/_shared/gstr3b.ts';
import {validateDraft,reconcile} from '../supabase/functions/gst-returns/validation.ts';
const context={gstin:'29FGHIJ5678K1Z1',period:'092026',role:'operator'};
const base=zeroBlanks(blank3b(context.gstin,context.period));
const row={source:'Platform',document:'INV-1',date:'2026-09-10',supplierGstin:'29ABCDE1234F1Z5',recipientGstin:'',operatorGstin:context.gstin,pos:'29',treatment:'section9_5',kind:'invoice',originalDocument:'',originalPeriod:'',taxable:100,igst:0,cgst:2.5,sgst:2.5,cess:0};
const build=rows=>addOperatorPlatform3b(base,rows,context);
// All four operator supplier/recipient combinations contribute to 3.1.1(i).
const categories=[row,{...row,document:'INV-2',recipientGstin:'29KLMNO1234P1Z5'},{...row,document:'INV-3',supplierGstin:''},{...row,document:'INV-4',supplierGstin:'',recipientGstin:'29KLMNO1234P1Z5'}];
const draft=build(categories);
assert.deepEqual(draft.eco_dtls,{eco_sup:{txval:400,iamt:0,camt:10,samt:10,csamt:0},eco_reg_sup:{txval:0}});
assert.deepEqual(draft.sup_details,base.sup_details,'Collected supplies must not become ordinary operator turnover');
assert.equal(base.eco_dtls,undefined,'Builder must not mutate existing draft');
assert.equal(validateDraft(draft,'gstr-3b',context.gstin,context.period),draft);
assert.equal(reconcile(draft,draft,'gstr-3b').matched,true);
const changed=structuredClone(draft);changed.eco_dtls.eco_sup.camt=9;
assert.equal(reconcile(draft,changed,'gstr-3b').matched,false);
const credit={...row,document:'CN-1',kind:'credit_note',originalDocument:row.document,taxable:20,cgst:0.5,sgst:0.5};
const debit={...credit,document:'DN-1',kind:'debit_note'};
assert.equal(build([row,credit]).eco_dtls.eco_sup.txval,80);
assert.equal(build([row,credit,debit]).eco_dtls.eco_sup.txval,100);
assert.throws(()=>build([credit]),/matching/);
assert.throws(()=>build([row,{...credit,recipientGstin:'29KLMNO1234P1Z5'}]),/matching/);
assert.throws(()=>build([row,{...credit,originalPeriod:'082026'}]),/Earlier-period/);
assert.throws(()=>build([row,{...credit,date:'2026-09-09'}]),/matching/);
assert.throws(()=>build([{...row,supplierGstin:''},{...credit,supplierGstin:''}]),/unregistered/);
assert.throws(()=>build([row,{...credit,taxable:60},{...credit,document:'CN-2',taxable:60}]),/exceed/);
assert.throws(()=>build([row,{...row,source:'POS'}]),/duplicate/);
assert.throws(()=>build([row,{...row,taxable:99}]),/conflicting/);
assert.throws(()=>build([row,{...row,document:'INV-2',treatment:'section52'}]),/TCS/);
assert.throws(()=>build([{...row,kind:'amendment',originalDocument:'OLD',originalPeriod:'082026'}]),/original-versus-revised/);
assert.throws(()=>addOperatorPlatform3b(draft,[row],context),/already/);
assert.throws(()=>addOperatorPlatform3b(base,[row],{...context,role:'seller'}),/operator workspace/);
assert.throws(()=>addOperatorPlatform3b({...base,gstin:row.supplierGstin},[row],context),/account/);
assert.throws(()=>build([]),/imported documents/);
console.log('Operator draft scenarios passed: four supply categories, linked notes, duplicate/conflict rejection, section-52 isolation, amendment blocking and full-content reconciliation.');
