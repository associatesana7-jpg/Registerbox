import assert from 'node:assert/strict';
import { amount, buildGstReview } from '../src/lib/gst-review.ts';
assert.equal(amount(null), null);
assert.equal(amount(''), null);
assert.equal(amount(false), null);
assert.equal(amount(0), 0);
assert.equal(amount('125.50'), 125.5);
const gstin = 'TEST-GSTIN';
const period = '082026';
const data = { status_cd: '1', data: { gstin, ret_period: period, sec_sum: [{ sec_nm: 'B2B', ttl_rec: 0, ttl_tax: 0 }] } };
const review = buildGstReview(data, 'gstr-1', gstin, period);
assert.equal(review.identityMatches, true);
assert.equal(review.sections[0].rows.find(row => row.label === 'Taxable value').value, 0);
assert.equal(review.sections[0].rows.find(row => row.label === 'IGST').value, null);
assert.equal(buildGstReview(data,'gstr-1','DIFFERENT',period).identityMatches,false);
assert.equal(buildGstReview(data,'gstr-1',gstin,'072026').identityMatches,false);
assert.equal(buildGstReview({},'gstr-1',gstin,period).sections.length,0);
const threeB = buildGstReview({ data: { gstin, ret_period: period, sup_details: { osup_det: { txval: 100, iamt: 18, camt: 0, samt: 0, csamt: 0 } }, itc_elg: { itc_net: { iamt: 5, camt: 0, samt: 0, csamt: 0 } } } }, 'gstr-3b', gstin, period);
assert.equal(threeB.sections.length,2);
assert.equal(threeB.sections[0].rows[0].value,100);
assert.equal(threeB.warnings.length,0);
console.log('GST review tests passed: missing/zero, envelope, identity, period and GSTR-3B sections.');
