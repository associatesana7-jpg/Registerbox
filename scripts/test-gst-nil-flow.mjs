import assert from 'node:assert/strict';
import {nilNextStep} from '../src/lib/gst-nil-flow.ts';
const draft={form:'gstr-1',state:'draft',reconciliation:null,snapshot_at:null,reference_id:null};
assert.equal(nilNextStep(null),'eligibility');
assert.equal(nilNextStep(draft),'proceed');
const checked={...draft,reconciliation:{matched:true},snapshot_at:new Date().toISOString()};
assert.equal(nilNextStep(checked),'proceed');
assert.equal(nilNextStep({...checked,state:'proceed_pending'}),'poll');
assert.equal(nilNextStep({...checked,state:'proceed_pending',reference_id:'accepted-ref'}),'review');
assert.equal(nilNextStep({...draft,state:'prepared'}),'review');
assert.equal(nilNextStep({...checked,state:'prepared'}),'review');
assert.equal(nilNextStep({...checked,form:'gstr-3b',state:'prepared'}),'review');
assert.equal(nilNextStep({...checked,state:'otp_sent'}),'otp');
assert.equal(nilNextStep({...checked,state:'filed'}),'complete');
assert.equal(nilNextStep({...checked,state:'unknown'}),'blocked');
assert.equal(nilNextStep({...draft,form:'gstr-3b'}),'review');
assert.equal(nilNextStep({...draft,state:'prepared',snapshot_at:'invalid'}),'review');
assert.equal(nilNextStep({...draft,state:'blocked'}),'blocked');
assert.equal(nilNextStep({...draft,state:'blocked',last_error:'GST rejected (RET00003)'}),'recover');
console.log('Nil journey transitions passed: declaration, preparation, processing, OTP and completion without a summary-fetch prerequisite.');
